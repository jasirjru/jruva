// Real integrated Next.js -> FastAPI -> SQLite/storage, with fake inference only.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { chromium } from 'playwright';

const base = 'http://127.0.0.1:33587';
const backend = 'http://127.0.0.1:38197';
const { token } = JSON.parse(fs.readFileSync('../scratch/assembly-browser/auth.json', 'utf8'));
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext();
await context.addCookies([{ name: 'access_token', value: token, url: base, httpOnly: true, sameSite: 'Lax' }]);
await context.route('**/*', route => {
  const url = new URL(route.request().url());
  return url.origin === base ? route.continue() : route.abort();
});
const checks = [];
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); };
const page = await context.newPage();
const images = [], chats = [];
page.on('request', request => {
  if (request.url().endsWith('/api/v1/image/generate')) images.push(request.headers()['idempotency-key']);
  if (request.url().endsWith('/api/v1/chat') && request.method() === 'POST') chats.push(request.postDataJSON().conversation_id);
});
const calls = async () => (await (await context.request.get(`${backend}/__assembly_stats`)).json()).synthetic_provider_calls;
try {
  await page.goto(base);
  await page.getByTitle('Images Studio & Gallery', { exact: true }).click();
  await page.locator('#image-prompt-input').fill('A synthetic blue house');
  await page.getByRole('button', { name: /Generate Image/ }).click();
  await page.waitForFunction(() => document.querySelector('#image-prompt-input')?.value === '');
  check('real authenticated image persists and charges once', await calls() === 1);
  check('real private content image renders', await page.locator('.workspace-content-grid img').count() > 0);
  await page.locator('.workspace-modal-overlay').click({ position: { x: 10, y: 10 } });
  await page.locator('#image-prompt-input').fill('A synthetic blue house');
  await page.getByRole('button', { name: /Generate Image/ }).click();
  await page.waitForFunction(() => document.querySelector('#image-prompt-input')?.value === '');
  check('fresh identical studio intent dispatches independently', await calls() === 2 && images[0] !== images[1]);
  await page.locator('.workspace-modal-overlay').click({ position: { x: 10, y: 10 } });
  await page.locator('#image-prompt-input').fill('A synthetic unknown house');
  await page.getByRole('button', { name: /Generate Image/ }).click();
  await page.waitForFunction(() => document.querySelector('.workspace-status-banner')?.textContent.includes('unknown'));
  check('real unknown dispatch retained', await calls() === 3);
  await page.reload();
  await page.getByTitle('Images Studio & Gallery', { exact: true }).click();
  await page.locator('#image-prompt-input').fill('A synthetic unknown house');
  await page.getByRole('button', { name: /Generate Image/ }).click();
  await page.waitForFunction(() => document.querySelector('.workspace-status-banner')?.textContent.includes('No generation was repeated'));
  check('real unknown retry after reload never repeats provider', await calls() === 3 && images[2] === images[3]);
  await page.getByRole('button', { name: /Back to Chat/ }).click();
  await page.locator('textarea').first().fill('Generate a photorealistic synthetic blue house');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).last().waitFor();
  await page.getByRole('button', { name: 'Stop generation', exact: true }).waitFor({ state: 'hidden' });
  check('real image intent chat routes to fenced provider', await calls() === 4);
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).last().click();
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).last().waitFor();
  await page.getByRole('button', { name: 'Stop generation', exact: true }).waitFor({ state: 'hidden' });
  check('real completed chat regeneration creates fresh intent', await calls() === 5 && chats[0] !== chats[1]);
  await page.locator('textarea').first().fill('Generate a photorealistic synthetic unknown house');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await page.getByText(/Synthetic accepted operation outcome unknown/).first().waitFor();
  await page.getByRole('button', { name: 'Stop generation', exact: true }).waitFor({ state: 'hidden' });
  const unknownRetryResponse = page.waitForResponse(response => response.url().endsWith('/api/v1/chat'));
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).last().click();
  await unknownRetryResponse;
  await page.getByText(/No generation was repeated/).first().waitFor();
  check('real unknown chat retry preserves identity and single dispatch', await calls() === 6 && chats[2] === chats[3]);
  await page.getByRole('button', { name: 'Stop generation', exact: true }).waitFor({ state: 'hidden' });
  await page.reload();
  await page.getByText(/No generation was repeated/).last().waitFor();
  const restored = page.waitForResponse(response => response.url().endsWith('/api/v1/chat'));
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).last().click();
  await restored;
  await page.getByRole('button', { name: 'Stop generation', exact: true }).waitFor({ state: 'hidden' });
  check('real restored unknown chat preserves durable intent', await calls() === 6 && chats[3] === chats[4]);
  await page.evaluate(() => {
    for (const key of Object.keys(sessionStorage)) if (key.startsWith('jruva:chat-intent:')) sessionStorage.removeItem(key);
  });
  await page.reload();
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).last().waitFor();
  const missing = page.waitForResponse(response => response.url().endsWith('/api/v1/chat'));
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).last().click();
  await missing;
  await page.getByText(/no recoverable intent identity/).last().waitFor();
  await page.getByRole('button', { name: 'Stop generation', exact: true }).waitFor({ state: 'hidden' });
  check('restored history without receipt refuses new image dispatch', await calls() === 6);
  await page.reload();
  await page.getByText(/no recoverable intent identity/).last().waitFor();
  const refusedAgain = page.waitForResponse(response => response.url().endsWith('/api/v1/chat'));
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).last().click();
  await refusedAgain;
  check('missing-history refusal remains safe across another reload', await calls() === 6);
  await page.screenshot({ path: '../scratch/assembly-browser/real-integrated.png' });
  const result = { passed: checks.length, failed: 0, checks, inference: 'deterministic fake', database: 'isolated SQLite', externalEgress: 'blocked' };
  fs.writeFileSync('../scratch/assembly-browser/backend-results.json', JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
} finally { await browser.close(); }
